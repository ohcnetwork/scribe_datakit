#!/usr/bin/env python3
"""Export metadata.json + audio/ → a HuggingFace `audiofolder` dataset in hf/.

Transcodes to 16 kHz mono FLAC. The webm/opus originals are NOT shipped: HF's Audio
feature decodes with libsndfile (no WebM support at all), and these files carry no
duration header — the same pathology the app works around. FLAC decodes everywhere
and is what LibriSpeech ships; ASR models resample to 16 kHz anyway.

Corrupt clips are excluded by default: their broken container timestamps make ffmpeg
gap-fill silence to 24h+ (see build_metadata.compute_duration). As a backstop every
transcode is hard-capped at the known duration and the output is re-probed — a FLAC
whose length disagrees with metadata.json is dropped rather than published.

Incremental: a clip whose .flac already exists is skipped, so re-runs are near-instant.
Needs the audio locally — run `make pull` first. Push with the `hf` CLI, see
docs/huggingface.md.

    python hf_export.py                      # all healthy clips
    python hf_export.py --min-status final   # only clips approved for training
    python hf_export.py --include-corrupt --force
"""
import argparse, json, os, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(__file__)
AUDIO_DIR = os.path.join(HERE, "audio")
META = os.path.join(HERE, "metadata.json")
HF_DIR = os.path.join(HERE, "hf")
DATA_DIR = os.path.join(HF_DIR, "data", "train")

SR = 16000          # ASR standard; models resample to this regardless
DUR_TOLERANCE = 1.0  # seconds of slack when checking the transcode against metadata

# columns published to metadata.jsonl; `file_name` is HF's magic column (→ Audio feature)
COLUMNS = ("id", "collection", "whisper_language", "spoken_languages",
           "generated_transcript", "generated_translation", "final_transcript",
           "final_translation", "duration_sec", "confidence", "no_speech_prob",
           "status", "category", "model", "recorded_at")
STATUS_RANK = {"reviewed": 1, "qa_complete": 2, "final": 3}   # pending/flagged rank below all


def select_clips(clips, min_status=None, include_corrupt=False):
    """Which clips make it into the dataset."""
    out = []
    for c in clips:
        if c.get("corrupt") and not include_corrupt:
            continue
        if min_status and STATUS_RANK.get(c.get("status"), 0) < STATUS_RANK[min_status]:
            continue
        if not c.get("duration_sec"):          # never probed / zero-length
            continue
        out.append(c)
    return out


def row(c):
    """Project a metadata.json clip → an audiofolder metadata.jsonl row."""
    r = {"file_name": f"{c['id']}.flac"}
    r.update({k: c.get(k) for k in COLUMNS})   # no fallback: machine and human text stay apart
    return r


def probe_duration(path):
    try:
        out = subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration",
             "-of", "csv=p=0", path],
            capture_output=True, text=True, timeout=60).stdout.strip()
        return float(out)
    except (ValueError, subprocess.SubprocessError):
        return None


def transcode(c, force=False):
    """webm/opus → 16 kHz mono FLAC. Returns the clip on success, None if dropped."""
    src = os.path.join(AUDIO_DIR, c["filename"])
    dst = os.path.join(DATA_DIR, f"{c['id']}.flac")
    if os.path.exists(dst) and not force:
        return c                                    # incremental: already done
    if not os.path.exists(src):
        print(f"  missing audio {c['filename']}", file=sys.stderr)
        return None

    want = c["duration_sec"]
    cmd = ["ffmpeg", "-v", "error", "-y", "-err_detect", "ignore_err", "-i", src,
           "-vn", "-ac", "1", "-ar", str(SR),
           "-t", str(want + DUR_TOLERANCE),         # hard cap: never emit a gap-filled 24h file
           "-c:a", "flac", dst]
    try:
        subprocess.run(cmd, capture_output=True, timeout=600, check=True)
    except subprocess.SubprocessError as e:
        print(f"  transcode failed {c['id']}: {e}", file=sys.stderr)
        return None

    got = probe_duration(dst)
    if got is None or abs(got - want) > max(DUR_TOLERANCE, 0.05 * want):
        print(f"  duration mismatch {c['id']}: flac {got}s vs metadata {want}s — dropped",
              file=sys.stderr)
        os.remove(dst)
        return None
    return c


CARD = """---
license: {license}
pretty_name: Scribe Audio Collection
task_categories:
- automatic-speech-recognition
language:
{langs}
size_categories:
- {size}
configs:
- config_name: default
  data_files:
  - split: train
    path: data/train/*
---

# Scribe Audio Collection

{n} scribing audio clips ({hours:.1f} h), 16 kHz mono FLAC, with transcripts.

Generated by `hf_export.py` from the upstream corpus — do not edit this repo by
hand; corrections flow through the source project and are re-exported.

## Fields

| Field | Meaning |
|---|---|
| `audio` | 16 kHz mono FLAC (transcoded from the webm/opus original) |
| `collection` | which collection the clip belongs to |
| `generated_transcript` | Whisper output in the spoken language; machine text |
| `generated_translation` | Whisper English translation; machine text, null for English-only audio |
| `final_transcript` | human-reviewed transcript; null until reviewed |
| `final_translation` | human-reviewed English translation; null until reviewed |
| `whisper_language` | Whisper's language guess; unreliable |
| `spoken_languages` | human-confirmed languages; null until confirmed |
| `status` | `pending`, `reviewed`, `qa_complete`, `final` (approved for training), or `flagged` |
| `confidence` | mean `exp(avg_logprob)` over Whisper segments, 0..1 |
| `no_speech_prob` | mean no-speech probability over segments, 0..1 |
| `category`, `duration_sec`, `model`, `recorded_at` | as derived upstream |

`generated_*` is always machine text and `final_*` is always human-reviewed. English-only
audio has no translation, so use `final_transcript` as its English text. For training,
filter to final rows:

```python
from datasets import load_dataset
ds = load_dataset("{repo}", split="train").filter(lambda r: r["status"] == "final")
```

## Notes

Clips with corrupt container timestamps are excluded from this export. Every FLAC's
duration is verified against the source manifest before publication.
"""


def write_card(clips, license_, repo):
    langs = sorted({l for c in clips
                    for l in c.get("spoken_languages") or [c.get("whisper_language")] if l}) or ["en"]
    hours = sum(c["duration_sec"] for c in clips) / 3600
    n = len(clips)
    size = "n<1K" if n < 1000 else ("1K<n<10K" if n < 10000 else "10K<n<100K")
    card = CARD.format(
        license=license_, size=size, n=n, hours=hours, repo=repo,
        langs="\n".join(f"- {l}" for l in langs))
    with open(os.path.join(HF_DIR, "README.md"), "w") as f:
        f.write(card)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-status", choices=STATUS_RANK,
                    help="only clips at this status or later (never pending/flagged)")
    ap.add_argument("--include-corrupt", action="store_true", help="include clips with corrupt timestamps")
    ap.add_argument("--force", action="store_true", help="re-transcode every clip")
    ap.add_argument("--license", default="cc-by-4.0")
    ap.add_argument("--repo", default=os.environ.get("HF_REPO", "gigincg/scribe_dataset"))
    args = ap.parse_args()

    with open(META) as f:
        clips = json.load(f)["clips"]
    picked = select_clips(clips, args.min_status, args.include_corrupt)
    print(f"{len(clips)} clips in manifest, exporting {len(picked)}", file=sys.stderr)

    os.makedirs(DATA_DIR, exist_ok=True)
    with ThreadPoolExecutor(max_workers=8) as ex:
        done = [c for c in ex.map(lambda c: transcode(c, args.force), picked) if c]

    with open(os.path.join(DATA_DIR, "metadata.jsonl"), "w") as f:
        for c in done:
            f.write(json.dumps(row(c)) + "\n")
    write_card(done, args.license, args.repo)

    hours = sum(c["duration_sec"] for c in done) / 3600
    print(f"wrote {HF_DIR}: {len(done)} clips, {hours:.1f}h "
          f"({len(picked) - len(done)} dropped)", file=sys.stderr)


if __name__ == "__main__":
    main()
